/** 클라이언트에 미리 보내는 문제(정답 없음). 정답과 해설은 채점하는 순간에 따로 보낸다. */
export interface PublicQ { text: string; options: string[]; unit: number; level: QLevel }
/** 서버가 출제용으로 고른 문제(보기가 섞여 있고 정답 번호를 안다) */
export interface PickedQ extends PublicQ { answer: number; explain: string }

export interface ChemFilter { units: number[]; levels: QLevel[] }

/** 교사가 보낸 문제은행을 검사해 쓸 수 있는 문제만 남긴다. */
export function cleanBank(raw: unknown): BankQ[] {
  if (!Array.isArray(raw)) return [];
  const out: BankQ[] = [];
  const str = (v: unknown, max: number) => (typeof v === 'string' ? v.trim().slice(0, max) : '');
  for (const r of raw.slice(0, 500)) {
    if (!r || typeof r !== 'object') continue;
    const o = r as Record<string, unknown>;
    const text = str(o.text, 400);
    const options = Array.isArray(o.options) ? o.options.map((x) => str(x, 120)) : [];
    const answer = Number(o.answer);
    if (!text || options.length !== 4 || options.some((x) => !x) || !(answer >= 0 && answer <= 3)) continue;
    out.push({
      id: str(o.id, 40) || `q${out.length}`,
      unit: ALL_UNITS.includes(Number(o.unit)) ? Number(o.unit) : 3,
      level: o.level === 'easy' || o.level === 'hard' ? o.level : 'normal',
      text, options, answer: Math.floor(answer), explain: str(o.explain, 600),
    });
  }
  return out;
}

/**
 * 조건에 맞는 문제를 n개 뽑고 보기를 섞는다. keep개만 남기면(미로용 3지선다) 정답 + 오답 일부만 쓴다.
 * 조건에 맞는 문제가 모자라면 은행 전체에서, 그래도 모자라면 기본 문제에서 채운다.
 */
export function pickQuestions(bank: BankQ[], f: ChemFilter, n: number, rand: () => number, keep = 4, avoid: Set<string> = new Set()): (PickedQ & { id: string })[] {
  const shuffle = <T,>(a: T[]) => { const o = [...a]; for (let i = o.length - 1; i > 0; i--) { const k = Math.floor(rand() * (i + 1)); [o[i], o[k]] = [o[k], o[i]]; } return o; };
  const match = (b: BankQ) => f.units.includes(b.unit) && f.levels.includes(b.level);
  let pool = shuffle(bank.filter(match));
  // 이번 경기에서 아직 안 나온 문제를 앞에 둔다
  pool = [...pool.filter((b) => !avoid.has(b.id)), ...pool.filter((b) => avoid.has(b.id))];
  if (pool.length < n) pool = [...pool, ...shuffle(bank.filter((b) => !match(b)))];
  if (pool.length < n) pool = [...pool, ...shuffle(DEFAULT_BANK)];
  return pool.slice(0, n).map((b) => {
    const wrong = shuffle(b.options.map((_, i) => i).filter((i) => i !== b.answer)).slice(0, keep - 1);
    const order = shuffle([b.answer, ...wrong]);
    return { id: b.id, text: b.text, options: order.map((i) => b.options[i]), answer: order.indexOf(b.answer), explain: b.explain, unit: b.unit, level: b.level };
  });
}
